// ===== Мобильное меню =====
function initBurger() {
    const burger = document.getElementById('burger');
    const nav = document.querySelector('.nav-list');
    burger.addEventListener('click', () => {
        burger.classList.toggle('active');
        nav.classList.toggle('active');
    });
    nav.querySelectorAll('a').forEach(a => {
        a.addEventListener('click', () => {
            burger.classList.remove('active');
            nav.classList.remove('active');
        });
    });
}

// ===== Кнопка «наверх» =====
function initScrollTop() {
    const btn = document.getElementById('scrollTop');
    window.addEventListener('scroll', () => {
        btn.classList.toggle('visible', window.scrollY > 400);
    });
}

function scrollToTop() {
    window.scrollTo({ top: 0, behavior: 'smooth' });
}

// ===== Появление секций =====
function initReveal() {
    const items = document.querySelectorAll('.section');
    const io = new IntersectionObserver((entries) => {
        entries.forEach(e => {
            if (e.isIntersecting) {
                e.target.classList.add('revealed');
                io.unobserve(e.target);
            }
        });
    }, { threshold: 0.12 });
    items.forEach(s => { s.classList.add('reveal'); io.observe(s); });
}

// ===== Ежедневная ротация статей =====
function renderDailyArticles() {
    const grid = document.querySelector('.articles-grid');
    if (!grid || !ARTICLE_BANK.length) return;

    // Детерминированный выбор: день года + 6-часовой слот определяют сдвиг в банке.
    // Так новости на главной обновляются 4 раза в день.
    const now = new Date();
    const startOfYear = new Date(now.getFullYear(), 0, 1);
    const dayOfYear = Math.floor((now - startOfYear) / 86400000);
    const slot = Math.floor(now.getHours() / 6);
    const offset = (dayOfYear * 4 + slot) % ARTICLE_BANK.length;

    const today = [];
    for (let i = 0; i < VISIBLE_ARTICLES; i++) {
        today.push({ article: ARTICLE_BANK[(offset + i) % ARTICLE_BANK.length], idx: (offset + i) % ARTICLE_BANK.length });
    }

    grid.innerHTML = today.map(({ article: a, idx }, i) => `
        <article class="article-card${i === 0 ? ' featured' : ''}">
            <a href="/articles/article-${idx + 1}.html" class="card-link"></a>
            <span class="tag">${a.tag}</span>
            <h3>${a.title}</h3>
            <p>${a.text}</p>
            <span class="article-meta">${a.readTime} мин · ${dateLabel(i)}</span>
        </article>
    `).join('');
}

// Подпись даты: сегодня / вчера / N дней назад
function dateLabel(daysAgo) {
    const names = ['сегодня', 'вчера', '2 дня назад', '3 дня назад', '4 дня назад', '5 дней назад', '6 дней назад'];
    return names[daysAgo] || daysAgo + ' дней назад';
}

// ===== Подписка =====
function initSubscribe() {
    const form = document.getElementById('subscribeForm');
    const note = document.getElementById('subscribeNote');
    form.addEventListener('submit', function (e) {
        e.preventDefault();
        const email = document.getElementById('emailInput').value.trim();
        if (!email) return;

        let subs = [];
        try { subs = JSON.parse(localStorage.getItem('ap_subscribers') || '[]'); } catch (err) {}
        if (!subs.includes(email)) {
            subs.push(email);
            localStorage.setItem('ap_subscribers', JSON.stringify(subs));
        }

        note.textContent = '✓ Спасибо! Вы подписаны на еженедельный дайджест.';
        note.style.color = '#2d9a6e';
        form.reset();
    });
}

