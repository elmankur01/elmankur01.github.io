// ===== Мобильное меню (Глобальное делегирование кликов) =====
function initBurger() {
    document.addEventListener('click', function (e) {
        const burgerBtn = e.target.closest('#burger') || e.target.closest('.burger');
        if (burgerBtn) {
            e.preventDefault();
            e.stopPropagation();
            const isOpen = burgerBtn.classList.toggle('active');
            const navList = document.querySelector('.nav-list') || document.getElementById('navList');
            if (navList) {
                navList.classList.toggle('active', isOpen);
                burgerBtn.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
            }
            return;
        }

        const activeNav = document.querySelector('.nav-list.active');
        if (activeNav) {
            if (e.target.closest('.nav-list a') || (!e.target.closest('.nav-list') && !e.target.closest('.burger'))) {
                activeNav.classList.remove('active');
                const burger = document.getElementById('burger') || document.querySelector('.burger');
                if (burger) {
                    burger.classList.remove('active');
                    burger.setAttribute('aria-expanded', 'false');
                }
            }
        }
    });
}

// ===== Кнопка «наверх» =====
function initScrollTop() {
    const btn = document.getElementById('scrollTop');
    if (!btn) return;
    btn.addEventListener('click', () => {
        window.scrollTo({ top: 0, behavior: 'smooth' });
    });
    window.addEventListener('scroll', () => {
        btn.classList.toggle('visible', window.scrollY > 400);
    });
}

// ===== Появление секций =====
function initReveal() {
    const items = document.querySelectorAll('.section');
    const io = new IntersectionObserver((entries) => {
        entries.forEach(e => {
            if (e.isIntersecting) {
                e.target.classList.add('revealed');
                io.unobserve(e.target);
            }
        });
    }, { threshold: 0.12 });
    items.forEach(s => { s.classList.add('reveal'); io.observe(s); });
}

// ===== Ежедневная ротация статей =====
// Детерминированный выбор: день года + 6-часовой слот определяют сдвиг в банке.
// Так новости на главной обновляются 4 раза в день.
function dayOffset() {
    const now = new Date();
    const startOfYear = new Date(now.getFullYear(), 0, 1);
    const dayOfYear = Math.floor((now - startOfYear) / 86400000);
    return dayOfYear % ARTICLE_BANK.length;
}

function slotOffset() {
    const now = new Date();
    const startOfYear = new Date(now.getFullYear(), 0, 1);
    const dayOfYear = Math.floor((now - startOfYear) / 86400000);
    const slot = Math.floor(now.getHours() / 6);
    return (dayOfYear * 4 + slot) % ARTICLE_BANK.length;
}

function escAttr(s) {
    return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

