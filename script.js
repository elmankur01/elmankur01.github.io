// Блок «Авто лайфхаки»: каждый день новый совет из банка TIPS (по дню года).
function renderTipOfDay() {
    const grid = document.getElementById('tipsGrid');
    if (!grid || !TIPS.length) return;
    const now = new Date();
    const startOfYear = new Date(now.getFullYear(), 0, 1);
    const dayOfYear = Math.floor((now - startOfYear) / 86400000);
    const t = TIPS[dayOfYear % TIPS.length];
    const num = (dayOfYear % TIPS.length) + 1;
    grid.innerHTML = `
        <article class="article-card">
            <span class="card-tag">Авто лайфхаки</span>
            <div class="card-body">
                <h3>${t.title}</h3>
                <p>${t.text}</p>
                <div class="card-meta">
                    <span class="article-meta">Совет №${num}/${TIPS.length} · новый каждый день</span>
                </div>
            </div>
        </article>`;
}

function renderDailyArticles() {
    const grid = document.getElementById('dailyGrid') || document.querySelector('.articles-grid');
    if (!grid || !ARTICLE_BANK.length) return;

    const offset = slotOffset();
    const html = [];
    for (let i = 0; i < VISIBLE_ARTICLES; i++) {
        const idx = (offset + i) % ARTICLE_BANK.length;
        const a = ARTICLE_BANK[idx];
        html.push(cardHTML(a, idx, i === 0, `${a.readTime} мин · ${dateLabel(i)}`));
    }
    grid.innerHTML = html.join('');
    if (typeof updateFavUI === 'function') updateFavUI();
}

// Подпись даты: сегодня / вчера / N дней назад
function dateLabel(daysAgo) {
    const names = ['сегодня', 'вчера', '2 дня назад', '3 дня назад', '4 дня назад', '5 дней назад', '6 дней назад'];
    return names[daysAgo] || daysAgo + ' дней назад';
}

// ===== Чтение статьи: индикатор прогресса и копирование ссылки =====
(function () {
    // Индикатор прогресса чтения
    const progress = document.querySelector('.reading-progress');
    if (!progress) return;

    const updateProgress = () => {
        const scrollTop = window.pageYOffset || document.documentElement.scrollTop;
        const docHeight = document.documentElement.scrollHeight - window.innerHeight;
        const percent = Math.max(0, Math.min(100, (scrollTop / docHeight) * 100));
        progress.style.width = percent + '%';
    };

    // Кнопка копирования ссылки
    const copyBtn = document.getElementById('copyBtn');
    if (copyBtn) {
        copyBtn.addEventListener('click', async () => {
            const url = window.location.href;
            try {
                await navigator.clipboard.writeText(url);
                copyBtn.textContent='Ссылка скопирована!';
                copyBtn.classList.add('copied');
                setTimeout(() => {
                    copyBtn.textContent = 'Скопировать ссылку';
                    copyBtn.classList.remove('copied');
                }, 2000);
            } catch (err) {
                // Fallback for older browsers
                const textarea = document.createElement('textarea');
                textarea.value = url;
                document.body.appendChild(textarea);
                textarea.select();
                document.execCommand('copy');
                document.body.removeChild(textarea);
                copyBtn.textContent='Ссылка скопирована!';
                copyBtn.classList.add('copied');
                setTimeout(() => {
                    copyBtn.textContent = 'Скопировать ссылку';
                    copyBtn.classList.remove('copied');
                }, 2000);
            }
        });
    }

    // Обновление прогресса при скролле
    window.addEventListener('scroll', updateProgress);
    // Инициализация при загрузке
    updateProgress();
})();

// ===== Мгновенный поиск и фильтр по рубрикам =====
function initSearchAndFilter() {
    const input = document.getElementById('articleSearch');
    const clearBtn = document.getElementById('clearSearchBtn');
    const filtersContainer = document.getElementById('categoryFilters');
    const meta = document.getElementById('searchMeta');
    const grid = document.getElementById('dailyGrid');
    if (!input || !filtersContainer || !grid) return;

    let activeTag = 'all';

    function update() {
        const query = input.value.trim().toLowerCase();
        if (clearBtn) clearBtn.hidden = !query;

        if (!query && activeTag === 'all') {
            if (meta) meta.hidden = true;
            renderDailyArticles();
            return;
        }

        const matches = ARTICLE_BANK.map((a, i) => ({ a, i })).filter(({ a }) => {
            const matchCategory = activeTag === 'all' || a.tag === activeTag;
            const matchQuery = !query ||
                a.title.toLowerCase().includes(query) ||
                a.text.toLowerCase().includes(query) ||
                a.tag.toLowerCase().includes(query);
            return matchCategory && matchQuery;
        });

        if (meta) {
            meta.hidden = false;
            let labelText = `Найдено статей: <strong>${matches.length}</strong>`;
            if (activeTag !== 'all') labelText += ` в рубрике «${activeTag}»`;
            if (query) labelText += ` по запросу «<em>${escAttr(query)}</em>»`;
            meta.innerHTML = labelText;
        }

        if (matches.length === 0) {
            grid.innerHTML = `
                <div class="no-results-card">
                    <h3>Ничего не найдено</h3>
                    <p>Попробуйте изменить поисковый запрос или выбрать другую рубрику.</p>
                </div>`;
        } else {
            grid.innerHTML = matches.map(({ a, i }, pos) => {
                return cardHTML(a, i, pos === 0, `${a.readTime} мин`);
            }).join('');
        }
        if (typeof updateFavUI === 'function') updateFavUI();
        if (typeof initLikes === 'function') initLikes();
    }

    input.addEventListener('input', update);

    if (clearBtn) {
        clearBtn.addEventListener('click', () => {
            input.value = '';
            update();
            input.focus();
        });
    }

    filtersContainer.querySelectorAll('.filter-btn').forEach(btn => {
        btn.addEventListener('click', () => {
            filtersContainer.querySelectorAll('.filter-btn').forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            activeTag = btn.dataset.tag || 'all';
            update();
        });
    });
}

